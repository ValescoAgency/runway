import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { preflight } from "./scaffolder-preflight.js";
import { writeDockerfile } from "./scaffolder-dockerfile.js";
import { buildAgentImage } from "./scaffolder-image.js";
import { applyVarlockLayer } from "./scaffolder-varlock.js";
import { verify } from "./scaffolder-verify.js";

/**
 * Which env-var name Claude Code reads for auth inside the container.
 * They are not interchangeable: api-key items hold `sk-ant-api03-…`
 * (pay-per-token), oauth items hold `sk-ant-oat01-…` (Pro/Max
 * subscription, generated by `claude setup-token`). Picking the wrong
 * one yields "Invalid API key" with no useful diagnostic.
 */
export type AuthMode = "api-key" | "oauth";

export const AUTH_MODE_ENV_VAR: Record<AuthMode, string> = {
  "api-key": "ANTHROPIC_API_KEY",
  oauth: "CLAUDE_CODE_OAUTH_TOKEN",
};

/**
 * Domain inputs for the scaffolder. Distinct from the CLI's
 * `InitOptions` (which lives in `commands/init.ts`) so the scaffolder
 * stays usable from contexts other than the CLI — programmatic
 * scaffolding, future hosted-runway, etc. The shape is 1:1 today;
 * the seam keeps future divergence cheap.
 */
export interface ScaffolderOptions {
  readonly tier: 1 | 2;
  readonly opVault?: string;
  readonly anthropicItem?: string;
  readonly ghTokenItem?: string;
  readonly authMode: AuthMode;
  readonly allowDirty: boolean;
  readonly force: boolean;
  readonly skipBuild: boolean;
}

const __dirname = dirname(fileURLToPath(import.meta.url));
// runway/src/scaffolder.ts → runway/templates/
export const TEMPLATES_DIR = join(__dirname, "..", "templates");

/**
 * Sanitize the cwd's basename the same way sandcastle's
 * `defaultImageName` does. Shared between buildAgentImage (writes
 * the tag) and verify (looks up the tag). Mirrors the diagnostics-
 * side helper of the same name; future cleanup could unify them via
 * a shared `src/image-name.ts` module.
 */
export function expectedImageName(cwd: string): string {
  const dirName =
    cwd
      .replace(/[\\/]+$/, "")
      .split(/[\\/]/)
      .pop() ?? "local";
  const sanitized =
    dirName.toLowerCase().replace(/[^a-z0-9_.-]/g, "-") || "local";
  return `sandcastle:${sanitized}`;
}

/**
 * Orchestrates the scaffold pipeline: preflight → dockerfile →
 * (tier 2: varlock layer) → (unless --skip-build: docker build) →
 * verify. Each phase prints its own progress; this composer just
 * sequences them and prints the "next steps" trailer.
 */
export async function scaffold(
  cwd: string,
  opts: ScaffolderOptions,
): Promise<void> {
  await preflight(cwd, opts);
  await writeDockerfile(cwd, opts);
  if (opts.tier === 2) {
    await applyVarlockLayer(cwd, opts);
  }
  if (!opts.skipBuild) {
    await buildAgentImage(cwd);
  }
  await verify(cwd, opts);

  console.log(`[runway init] done — tier ${opts.tier} scaffold applied`);
  console.log("[runway init] next steps:");
  console.log("  1. Review the diff (`git diff` and `git status`)");
  console.log("  2. Create a feature branch and commit");
  console.log("  3. Open a PR; merge after review");
  if (opts.tier === 2) {
    console.log(
      "  4. Confirm the op:// items exist in your 1Password vault before the first runway run",
    );
  }
}
